def wc(html: str) -> int:
    t = re.sub(r"\[[^\]]+\]", " ", html or "")
    t = re.sub(r"<[^>]+>", " ", t)
    t = html_lib.unescape(t)
    return len(re.findall(r"[\w\u0600-\u06FF]+", t))


def pick(key: str, options: list):
    h = int(hashlib.md5(key.encode("utf-8")).hexdigest(), 16)
    return options[h % len(options)]


