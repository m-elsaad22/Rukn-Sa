def update_post(pid: int, payload: dict) -> dict:
    r = requests.post(
        f"{BASE}/wp-json/wp/v2/posts/{pid}",
        auth=AUTH,
        headers=H,
        json=payload,
        timeout=120,
    )
    r.raise_for_status()
    return r.json()


def update_service(pid: int, payload: dict) -> dict:
    r = requests.post(
        f"{BASE}/wp-json/wp/v2/services/{pid}",
        auth=AUTH,
        headers=H,
        json=payload,
        timeout=120,
    )
    r.raise_for_status()
    return r.json()


def fetch_posts() -> list[dict]:
    posts = []
    page = 1
    while True:
        r = requests.get(
            f"{BASE}/wp-json/wp/v2/posts",
            auth=AUTH,
            headers=H,
            params={"per_page": 100, "page": page, "context": "edit", "status": "publish"},
            timeout=90,
        )
        if r.status_code != 200:
            break
        batch = r.json()
        if not batch:
            break
        posts.extend(batch)
        page += 1
    return posts


def featured_for(pid: int, kind: str) -> int:
    if kind == "clean":
        return CLEAN_MEDIA[pid % len(CLEAN_MEDIA)]
    return LEAK_MEDIA[pid % len(LEAK_MEDIA)]


def main():
    report = {"cities": [], "cleaning": [], "services": [], "skipped": []}
    posts = fetch_posts()

    # 1) City leak pages under ~1100 words
    for p in posts:
        title = p["title"]["raw"]
        city = extract_city(title)
        if not city:
            continue
        meta = get_meta(city)
        if not meta:
            report["skipped"].append({"id": p["id"], "city": city, "reason": "no-meta"})
            continue
        raw = (p.get("content") or {}).get("raw") or ""
        old = wc(raw)
        if old >= 1100:
            report["skipped"].append({"id": p["id"], "city": city, "reason": f"already-{old}"})
            continue
        content, excerpt = build_enriched_city(city, meta)
        new = wc(content)
        payload = {
            "content": content,
            "excerpt": excerpt,
            "featured_media": featured_for(p["id"], "leak"),
        }
        update_post(p["id"], payload)
        report["cities"].append(
            {"id": p["id"], "city": city, "old_wc": old, "new_wc": new, "featured": payload["featured_media"]}
        )
        print(f"CITY #{p['id']} {city} {old}->{new}")
        time.sleep(0.12)

    # 2) Cleaning posts
    by_id = {p["id"]: p for p in posts}
    for pid, conf in CLEANING.items():
        p = by_id.get(pid)
        if not p:
            # still try update
            pass
        raw = ""
        if p:
            raw = (p.get("content") or {}).get("raw") or ""
        old = wc(raw) if raw else 0
        content, excerpt = build_cleaning(pid, conf)
        new = wc(content)
        payload = {
            "content": content,
            "excerpt": excerpt,
            "featured_media": featured_for(pid, "clean"),
        }
        update_post(pid, payload)
        report["cleaning"].append({"id": pid, "title": conf["title"], "old_wc": old, "new_wc": new})
        print(f"CLEAN #{pid} {conf['title']} {old}->{new}")
        time.sleep(0.12)

    # 3) CPT services
    for pid, (title_ar, kind, blurb) in SERVICES.items():
        content, excerpt = build_service(title_ar, kind, blurb)
        payload = {
            "content": content,
            "excerpt": excerpt,
            "featured_media": SVC_MEDIA.get(kind, 10623),
        }
        update_service(pid, payload)
        report["services"].append({"id": pid, "title": title_ar, "words": wc(content)})
        print(f"SVC #{pid} {title_ar} wc={wc(content)}")
        time.sleep(0.12)

    out = ROOT / "data/content-enrich-results.json"
    out.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    summary = {
        "cities": len(report["cities"]),
        "cleaning": len(report["cleaning"]),
        "services": len(report["services"]),
        "skipped": len(report["skipped"]),
        "city_avg_new": round(sum(x["new_wc"] for x in report["cities"]) / max(1, len(report["cities"]))),
        "svc_avg": round(sum(x["words"] for x in report["services"]) / max(1, len(report["services"]))),
    }
    print(json.dumps(summary, ensure_ascii=False, indent=2))


