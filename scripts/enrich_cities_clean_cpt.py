def get_meta(city: str) -> dict | None:
    if city in CITY_META:
        return dict(CITY_META[city])
    if city in EXTRA_META:
        return dict(EXTRA_META[city])
    # soft match
    for k, v in {**CITY_META, **EXTRA_META}.items():
        if k in city or city in k:
            return dict(v)
    return None


def extract_city(title: str) -> str | None:
    m = re.search(r"كشف تسربات المياه في (.+?)(?:\s*\||$)", title)
    if not m:
        return None
    return m.group(1).strip()


