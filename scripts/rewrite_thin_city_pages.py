def extract_city_from_title(title: str) -> str | None:
    m = re.search(r"كشف تسربات المياه في (.+?)(?:\s*\||$)", title)
    return m.group(1).strip() if m else None


def main() -> None:
    limit = int(os.environ.get("REWRITE_LIMIT", "15"))
    dry = os.environ.get("DRY_RUN", "0") == "1"

    posts, _ = api("GET", f"{BASE}/wp/v2/posts?per_page=100&status=publish&context=edit")
    # paginate if needed
    # already <=100

    targets = []
    for p in posts:
        title = (p.get("title") or {}).get("raw") or ""
        raw = (p.get("content") or {}).get("raw") or ""
        wc = word_count(raw)
        city = extract_city_from_title(title)
        if city and city in CITIES and wc < 100:
            targets.append((p, city, wc))

    targets.sort(key=lambda x: x[2])
    targets = targets[:limit]
    print(f"Rewriting {len(targets)} thin city pages (limit={limit})")

    results = []
    for post, city, old_wc in targets:
        meta = CITIES[city]
        content = build_content(city, meta)
        new_wc = word_count(content)
        title = f"كشف تسربات المياه في {city} | شركة ركن التطور"
        payload = {
            "title": title,
            "content": content,
        }
        print(f"- {city}: {old_wc}w -> {new_wc}w id={post['id']}")
        if dry:
            results.append({"id": post["id"], "city": city, "old_wc": old_wc, "new_wc": new_wc, "dry": True})
            continue
        updated, code = api("POST", f"{BASE}/wp/v2/posts/{post['id']}", payload)
        results.append(
            {
                "id": post["id"],
                "city": city,
                "old_wc": old_wc,
                "new_wc": new_wc,
                "link": updated.get("link"),
                "code": code,
            }
        )
        time.sleep(0.2)

    out = Path("/tmp/rewrite_batch_results.json")
    out.write_text(json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {out}")
    print(json.dumps({"rewritten": len(results), "avg_new_wc": round(sum(r["new_wc"] for r in results) / max(len(results), 1))}, ensure_ascii=False))


if __name__ == "__main__":
    main()
