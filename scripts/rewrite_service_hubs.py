def load_index() -> list[dict]:
    posts = get_paged(
        "/wp/v2/posts",
        extra="&status=publish&_fields=id,slug,title,link",
    )
    out = []
    for p in posts:
        title = (p.get("title") or {}).get("rendered") or ""
        out.append({"id": p["id"], "title": title, "slug": p.get("slug"), "link": p.get("link")})
    return out


def city_links(hub: dict, index: list[dict], limit: int = 10) -> list[tuple[str, str]]:
    found: list[tuple[str, str]] = []
    for p in index:
        title = p["title"]
        if not any(n in title for n in hub["needles"]):
            continue
        city = None
        for c in CITIES:
            if c in title and c not in ("مكة", "المدينة"):
                city = c
                break
        if not city:
            continue
        found.append((f"{hub['svc']} في {city}", p["link"]))
        if len(found) >= limit:
            break
    return found


