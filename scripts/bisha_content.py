def _seed(slug: str) -> int:
    return int(hashlib.md5(slug.encode()).hexdigest()[:8], 16)


def _pick(seed: int, items: List[str], n: int = 1) -> List[str]:
    if not items:
        return []
    out = []
    for i in range(n):
        out.append(items[(seed + i * 7) % len(items)])
    return out


def arabic_word_count(html: str) -> int:
    text = re.sub(r"<[^>]+>", " ", html)
    return len(re.findall(r"[\u0600-\u06FF]+", text))


