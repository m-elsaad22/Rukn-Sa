def opener_window(plain: str, n: int = 220) -> str:
    return normalize_city_names(plain)[:n]


def first_chars(plain: str, n: int = 400) -> str:
    return normalize_city_names(plain)[:n]


def publish_all():
    results = []
    by_fam = defaultdict(list)
    for fam in INV["services"]:
        for city in INV["cities"]:
            target = INV["targets"][fam][city]
            if not target:
                results.append({"fam": fam, "city": city, "error": "missing target"})
                continue
            html = build_article(fam, city)
            words = ar_words(html)
            payload = {
                "content": html,
                "status": "publish",
                "excerpt": f"{SERVICE[fam]['name']} في {CITY[city]['ar']} — دليل محلي للتنفيذ والنطاق.",
            }
            put(f"/wp/v2/posts/{target['id']}", payload)
            plain = strip(html)
            by_fam[fam].append(
                {
                    "id": target["id"],
                    "city": city,
                    "op220": opener_window(plain, 220),
                    "op400": first_chars(plain, 400),
                    "words": words,
                }
            )
            row = {"id": target["id"], "fam": fam, "city": city, "slug": target["slug"], "words": words}
            results.append(row)
            print("OK", fam, city, target["id"], words, flush=True)
            time.sleep(0.15)

    sim_fails = []
    for fam, rows in by_fam.items():
        for i in range(len(rows)):
            for j in range(i + 1, len(rows)):
                a, b = rows[i], rows[j]
                if a["op220"] == b["op220"]:
                    sim_fails.append({"fam": fam, "a": a["city"], "b": b["city"], "type": "exact_opener"})
                ratio = SequenceMatcher(None, a["op400"], b["op400"]).ratio()
                if ratio >= 0.82:
                    sim_fails.append(
                        {
                            "fam": fam,
                            "a": a["city"],
                            "b": b["city"],
                            "type": "high_ratio",
                            "ratio": round(ratio, 3),
                        }
                    )

    out = {
        "phase": 1,
        "target_words": TARGET,
        "published": results,
        "under_3000": [r for r in results if r.get("words", 0) < TARGET],
        "similarity_fails": sim_fails,
        "oven_cleaning": "deferred_to_phase_2",
        "pass": len(results) == 40 and not [r for r in results if r.get("words", 0) < TARGET] and not sim_fails,
    }
    path = ROOT / "data" / "phase1-publish-results-2026-11-09.json"
    path.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")
    print("WROTE", path, flush=True)
    print(
        "SUMMARY",
        {"n": len(results), "under": len(out["under_3000"]), "sim_fails": len(sim_fails), "pass": out["pass"]},
        flush=True,
    )
    return out


