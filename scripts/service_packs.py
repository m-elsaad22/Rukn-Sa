import hashlib
from typing import Any


def hid(key: str) -> int:
    return int(hashlib.md5(key.encode("utf-8")).hexdigest(), 16)


def pick(key: str, options: list, offset: int = 0):
    if not options:
        return options
    return options[(hid(key) + offset) % len(options)]


def pick_n(key: str, options: list, n: int, offset: int = 0) -> list:
    if not options:
        return []
    n = min(n, len(options))
    start = (hid(key) + offset) % len(options)
    step = 3 if len(options) > 3 else 1
    idxs = []
    i = 0
    while len(idxs) < n and i < len(options) * 4:
        idx = (start + i * step) % len(options)
        if idx not in idxs:
            idxs.append(idx)
        i += 1
    if len(idxs) < n:
        for j in range(len(options)):
            if j not in idxs:
                idxs.append(j)
            if len(idxs) >= n:
                break
    return [options[i] for i in idxs[:n]]


